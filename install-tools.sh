#!/bin/bash
#
# install-tools.sh
#
# Installs the compilers, Qt 6 and libraries needed to build the
# AccessibleApps on Debian / Ubuntu, then (if needed) walks you through
# creating account-googleaccess.h for the apps that talk to Google
# (ContactManager and GoogleFetch).
#
# Usage:
#   ./install-tools.sh                    install tools, then Google setup if needed
#   ./install-tools.sh --google-account   only run the Google account setup
#

SCRIPTDIR="$(cd "$(dirname "$0")" && pwd)"
GOOGLEAPPS="ContactManager GoogleFetch"
QMAKE6="/usr/lib/qt6/bin/qmake"

# Use sudo only when not already root
SUDO=""
if [ "$(id -u)" -ne 0 ]; then SUDO="sudo"; fi


#
# Install the system packages
#
install_packages()
{
    if ! command -v apt-get >/dev/null 2>&1; then
        echo "ERROR: apt-get not found. This script supports Debian and Ubuntu only."
        echo "       Install the packages listed in README (QT6 under Linux) by hand."
        exit 1
    fi

    echo "Installing packages..."
    $SUDO apt-get update || exit 1
    $SUDO apt-get install -y \
        build-essential git libssl-dev \
        qt6-base-dev qt6-base-dev-tools qt6-5compat-dev qt6-multimedia-dev \
        gstreamer1.0-plugins-base gstreamer1.0-plugins-good \
        gstreamer1.0-libav gstreamer1.0-pulseaudio \
        libspa-0.2-bluetooth clang \
        || { echo "ERROR: package installation failed"; exit 1; }
}


#
# Make 'qmake' point at Qt 6 (dobuildlin.sh calls plain 'qmake')
#
setup_qmake()
{
    if [ ! -x "$QMAKE6" ]; then
        echo "ERROR: Qt 6 qmake not found at $QMAKE6"
        exit 1
    fi

    echo "Selecting Qt 6 qmake as the default 'qmake'..."
    $SUDO update-alternatives --install /usr/bin/qmake qmake "$QMAKE6" 60 || exit 1
    $SUDO update-alternatives --set qmake "$QMAKE6" || exit 1

    echo "qmake reports: $(qmake -query QT_VERSION 2>/dev/null)"
}


#
# Write account-googleaccess.h into one app folder
#
write_google_header()
{
    local header="$SCRIPTDIR/$1/account-googleaccess.h"

    # Create the file readable only by you, because it holds the secret
    (
        umask 077
        cat > "$header" <<EOF
#ifndef GOOGLEACESSACCOUNT_H
#define GOOGLEACESSACCOUNT_H

// Generated by install-tools.sh from account-googleaccess.h.example
// Created from the Google Cloud console - see https://console.cloud.google.com/

#define CLIENTID "$CLIENTID"
#define SECRET "$SECRET"

// People API   - https://www.googleapis.com/auth/contacts
// Calendar API - https://www.googleapis.com/auth/calendar
// Contact API  - https://www.google.com/m8/feeds/
// My Details   - profile email

// Currently using Calendar and Contacts APIs
// Google are migrating to People API
// Need my details to retrieve current user name

#define SCOPE "https://www.googleapis.com/auth/calendar https://www.googleapis.com/auth/contacts https://www.google.com/m8/feeds/ profile email"

#endif // GOOGLEACESSACCOUNT_H
EOF
    ) || { echo "ERROR: could not write $header"; return 1; }

    echo "Written $header (readable only by you)."
}


#
# Walk through creating account-googleaccess.h for each Google app
#
setup_google_account()
{
    local app
    local targets=()

    # Find the app folders that have been downloaded
    for app in $GOOGLEAPPS; do
        if [ -d "$SCRIPTDIR/$app" ]; then
            targets+=("$app")
        fi
    done

    if [ ${#targets[@]} -eq 0 ]; then
        echo ""
        echo "No Google-enabled app is downloaded yet, so account-googleaccess.h"
        echo "cannot be created. Run downloadapps-https.sh first, then:"
        echo "    ./install-tools.sh --google-account"
        return 1
    fi

    # Only create the headers that are missing, unless the user asks to replace them
    local missing=()
    for app in "${targets[@]}"; do
        if [ -f "$SCRIPTDIR/$app/account-googleaccess.h" ]; then
            echo "Found $app/account-googleaccess.h"
        else
            missing+=("$app")
        fi
    done

    if [ ${#missing[@]} -eq 0 ]; then
        if [ ! -t 0 ]; then return 0; fi
        read -r -p "Replace the existing credentials? [y/N] " answer
        case "$answer" in
            y|Y|yes|YES) missing=("${targets[@]}") ;;
            *) return 0 ;;
        esac
    fi

    cat <<'EOF'

The Google-enabled apps (ContactManager and GoogleFetch) sign in to Google
with your own OAuth client, so you need a Client ID and Client secret from
the Google Cloud console.  One set of credentials is used for all of them.

 1. Go to https://console.cloud.google.com/ and create a project (or pick
    an existing one).
 2. APIs & Services > Library: enable the "Google People API" and the
    "Google Calendar API".
 3. APIs & Services > OAuth consent screen: choose External, enter an app
    name and your email address, and add your Google account under
    "Test users".
 4. APIs & Services > Credentials > Create credentials > OAuth client ID.
    Application type: "TVs and Limited Input devices" (the apps use the
    Google device login flow, which needs this type).
 5. Copy the Client ID and the Client secret that Google shows you.

EOF

    echo "Headers to create: ${missing[*]}"
    echo ""

    if [ -t 0 ]; then
        read -r -p "Press Enter when you have them..." _
    fi

    CLIENTID=""
    SECRET=""

    for attempt in 1 2 3; do
        read -r -p "Client ID: " CLIENTID
        if [[ "$CLIENTID" =~ ^[A-Za-z0-9._-]+$ ]]; then break; fi
        echo "  Client ID should contain only letters, digits, '.', '_' or '-'."
        CLIENTID=""
    done

    for attempt in 1 2 3; do
        read -r -s -p "Client secret (input hidden): " SECRET
        echo ""
        if [[ "$SECRET" =~ ^[A-Za-z0-9._-]+$ ]]; then break; fi
        echo "  Client secret should contain only letters, digits, '.', '_' or '-'."
        SECRET=""
    done

    if [ -z "$CLIENTID" ] || [ -z "$SECRET" ]; then
        echo "ERROR: Client ID and secret are required. Nothing written."
        return 1
    fi

    for app in "${missing[@]}"; do
        write_google_header "$app" || return 1
    done

    echo "These files are listed in each app's .gitignore, so they will not be committed."
}


case "$1" in
    --google-account)
        setup_google_account
        exit $?
        ;;
    -h|--help)
        sed -n '2,11p' "$0"
        exit 0
        ;;
    "")
        install_packages
        setup_qmake
        echo ""
        setup_google_account
        ;;
    *)
        echo "Unknown option: $1"
        echo "Usage: ./install-tools.sh [--google-account]"
        exit 1
        ;;
esac

echo ""
echo "Tools installed. Next steps are in README (Starting from scratch)."
